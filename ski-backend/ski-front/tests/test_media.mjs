import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const source = await readFile(new URL('../utils/media.js', import.meta.url), 'utf8')
const { safeMediaUrl, authorizedImage, verificationLabel, normalizeMedia, createRequestGuard, budgetSummary, priceTerms, priceListNotice, priceConditions, formatMoney } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'))
for (const url of ['http://example.com', 'javascript:alert(1)', '//example.com', 'https://user:pass@example.com', 'https://example.com/has space', 'https://example.com/\\bad', null]) assert.equal(safeMediaUrl(url), '')
const media = { kind: 'photo', rights: 'authorized', verification: 'content_checked', url: 'https://example.com/page', image_url: 'https://example.com/image.jpg' }
assert.equal(authorizedImage(media), media.image_url)
for (const patch of [{ rights: 'link_only' }, { verification: 'page_checked' }, { kind: 'video' }, { image_url: undefined }, { image_url: 'javascript:bad' }]) assert.equal(authorizedImage({ ...media, ...patch }), '')
assert.equal(authorizedImage({ ...media, image_url: undefined }), '')
assert.equal(authorizedImage({ ...media, image_url: media.url }), '')
assert.equal(normalizeMedia([media, media]).length, 1)
assert.equal(normalizeMedia([{ ...media, verification: 'unknown' }]).length, 0)
assert.match(verificationLabel({ verification: 'page_checked' }), /不代表.*教学内容/)
assert.equal(normalizeMedia([{ ...media, rights: 'link_only' }])[0].image_url, '')
assert.equal(normalizeMedia([{ ...media, url: 'http://bad' }]).length, 0)
assert.deepEqual(budgetSummary({ items: [] }), { subtotal: 0, currency: 'CNY', subtotals: [], missing: [], uncountedOnly: false, pending: true })
assert.deepEqual(budgetSummary({ items: [{ amount: 0 }, { amount: 120 }] }), { subtotal: 120, currency: 'CNY', subtotals: [{ currency: 'CNY', total: 120 }], missing: [], uncountedOnly: false, pending: true })
assert.equal(budgetSummary({ currency: 'jpy', items: [{ amount: 5000, currency: 'JPY' }] }).currency, 'JPY')
const mixed = budgetSummary({ currency: 'CNY', missing: ['住宿'], items: [
  { amount: 650 }, { amount: 5000, currency: 'JPY' }, { amount: 51000, currency: 'JPY', counted: false }] })
assert.deepEqual(mixed.subtotals, [{ currency: 'CNY', total: 650 }, { currency: 'JPY', total: 5000 }])
assert.deepEqual(mixed.missing, ['住宿']); assert.equal(mixed.pending, true)
assert.equal(budgetSummary({ complete: true, items: [{ amount: 650 }] }).pending, false)
assert.equal(budgetSummary({ items: [{ amount: 5000, currency: 'JPY', counted: false, note: '不计入预算小计' }] }).uncountedOnly, true)
assert.deepEqual(priceTerms({ item: '全天雪票', price: 560, unit: '人/天' }), [])
assert.deepEqual(priceTerms({ valid_from: '2026-11-28', valid_to: '2027-03-30', unit_basis: 'per_seat_one_way', tax_status: 'included', excludes: ['unknown'], budget_usable: false }),
  ['适用 2026-11-28～2027-03-30', '单程每座（往返需另计）', '含税', '不含项未逐项说明', '仅供参考，不计入预算小计'])
assert.equal(formatMoney(5000, 'JPY'), 'JPY 5000'); assert.equal(formatMoney(560, undefined), '¥560')
assert.equal(priceListNotice([{ budget_usable: true }, { price: 560 }]), '')
assert.match(priceListNotice([{ budget_usable: false }]), /不能加总成完整旅行总价/)
assert.deepEqual(priceConditions({ conditions: [' 需预约 ', '', 1] }), ['需预约'])
assert.deepEqual(priceConditions({}), [])
const guard = createRequestGuard(); const old = guard.next(); const current = guard.next()
assert.equal(guard.current(old), false); assert.equal(guard.current(current), true)
guard.next(); assert.equal(guard.current(current), false)
const panel = await readFile(new URL('../components/MediaPanel.vue', import.meta.url), 'utf8')
assert.ok(panel.includes('authorizedImage(resource)')); assert.match(panel, /uni.previewImage/); assert.ok(panel.includes('slice(0, 3)'))
const actions = await readFile(new URL('../utils/media-actions.js', import.meta.url), 'utf8')
assert.match(actions, /noopener noreferrer/); assert.match(actions, /no-referrer/); assert.match(actions, /setClipboardData/)
console.log('Media helper and safety tests passed')
